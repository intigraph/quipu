"""Publish path-free evidence and derive paper tables from saved measurements."""

import argparse
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parents[1] / "docs" / "paper-merge"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    args = parser.parse_args()
    results = json.loads((args.input / "results.json").read_text())
    assert [r["seed"] for r in results] == [1, 7, 42, 99, 2026]
    destination = HERE / "results"
    destination.mkdir(exist_ok=True)
    for result in results:
        assert result["runtime"]["stopped"]
        result["runtime"] = {
            k: result["runtime"][k]
            for k in ("served_version", "host", "port", "stopped", "exit_code")
        }
        (destination / f"input-{result['seed']}.json").write_text(
            json.dumps(result.pop("cases"), indent=2) + "\n"
        )
    (destination / "metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    metric_names = [
        "decision_units",
        "false_decision_units",
        "fp_slots",
        "fn_slots",
        "triples_lost",
        "triples_spurious",
    ]
    latex = [
        "% Generated by just bench memory-report; do not edit counts.",
        "\\begin{table}[ht]\\centering\\small",
        "\\begin{tabular}{lrrrrrr}\\toprule",
        "Arm & Units & False units & FP slots & FN slots & Lost & Extra \\\\ \\midrule",
    ]
    md = [
        "# ARM F results",
        "",
        "Generated from real Dolt SQL-server runs, seeds 1, 7, 42, 99, 2026.",
        "All counts below are per seed; the balanced case counts are identical by design.",
        "",
        "| arm | units | false units | FP slots | FN slots | facts lost | facts extra |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    labels = {
        "json-native": "Dolt JSON",
        "whole-cell-text": "Whole-cell TEXT",
        "typed-rows": "Typed rows + provenance",
    }
    for arm, label in labels.items():
        columns = []
        for key in metric_names:
            values = [r["arms"][arm][key] for r in results]
            assert len(set(values)) == 1, "Use ranges if workload counts change"
            columns.append(str(values[0]))
        latex.append(label + " & " + " & ".join(columns) + " \\\\")
        md.append("| " + label + " | " + " | ".join(columns) + " |")
    latex += [
        "\\bottomrule\\end{tabular}",
        "\\caption{Arm F: 200 synthetic Memories per seed, 60 true conflict slots. "
        "All arms detect the 60 true slots. Units are native conflict rows; "
        "false units contain no oracle conflict; FP/FN use semantic slots. "
        "Lost/extra counts use automatic output with conflicted units held at base.}",
        "\\label{tab:memorymerge}\\end{table}",
        "",
        "\\begin{table}[ht]\\centering\\small",
        "\\begin{tabular}{lrr}\\toprule",
        "Competency query & JSON (ms) & Rows (ms) \\\\ \\midrule",
    ]
    md += [
        "",
        "Warm SQL latency: pooled median of 7 timed executions per seed (35 samples).",
        "Each execution returns independently constructed expected answers; plans are in metrics.json.",
        "",
        "| query | JSON median ms | rows median ms |",
        "| --- | ---: | ---: |",
    ]
    for query in ("status", "tag", "traversal"):
        columns = []
        for arm in ("json-native", "typed-rows"):
            samples = [
                sample
                for r in results
                for sample in r["query"]["queries"][query][arm]["samples_ms"]
            ]
            columns.append(f"{statistics.median(samples):.3f}")
        latex.append(query.capitalize() + " & " + " & ".join(columns) + " \\\\")
        md.append("| " + query + " | " + " | ".join(columns) + " |")
    latex += [
        "\\bottomrule\\end{tabular}",
        "\\caption{Arm F warm SQL latency, pooled median of 35 executions on "
        "2,000 Memories, 10,000 metadata facts and 2,000 Links per seed. "
        "One local fixture; these are workload-specific timings.}",
        "\\label{tab:memoryquery}\\end{table}",
    ]
    md += [
        "",
        "Dolt 2.1.8; every fixture stopped and its loopback port closed after the run.",
        "Five invalid-type candidates per seed were rejected by the prototype writer before mutation;",
        "native JSON accepted those same values. This is a writer guard, not native SHACL enforcement.",
        "",
        "The TEXT arm is an ablation, not the behavior of current Dolt JSON. Native JSON already",
        "merges independent object keys. Typed rows avoid concurrent set-addition conflicts, but",
        "set_in_version makes identical semantic values with distinct provenance versions conflict.",
        "Neither total native decisions nor entirely false native decisions decreases against JSON in this workload.",
        "The slot counts expand a conflicted JSON/TEXT Memory to its changed metadata keys; they",
        "do not claim Dolt exposes a distinct prompt for each JSON key. Loss includes deferred valid",
        "changes under the common hold-at-base convention, not a claim of irreversible deletion.",
        "",
        "Seeds change labels/order and query populations; they do not change the balanced ten-template",
        "merge workload. Bodies are unchanged. The trial is synthetic and says nothing about production",
        "conflict frequency. The prior 0/93 alias blindness, negative Arm D, and single-deployment limit stand.",
    ]
    (PAPER / "sections" / "06-memory-tables.tex").write_text("\n".join(latex) + "\n")
    (HERE / "RESULTS.md").write_text("\n".join(md) + "\n")
    print("Published path-free metrics, five input corpora and generated paper tables")


if __name__ == "__main__":
    main()
