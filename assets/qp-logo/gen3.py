#!/usr/bin/env python3
"""Round 3: three-line qp, a ringed sun to the right, a slanted db shadow. Writes qp-sun.pxl."""
import json
import gen2 as g2

NIGHT, TEAL, YELLOW, ORANGE, PINK, CREAM = "#14121F", "#00C2A8", "#FFC914", "#FF5A1F", "#FF2E88", "#FFF4DC"
COLS = {"wall": NIGHT, "floor": TEAL, "sun3": PINK, "sun2": ORANGE, "sun1": YELLOW,
        "line1": YELLOW, "line2": ORANGE, "line3": PINK, "knot": CREAM}

def build(W, x0, y0, sh_h, sun, radii, horizon_cut):
    g2.W = W
    g = y0 + g2.TALL
    grid = [["wall" if y < g else "floor" for _ in range(W)] for y in range(g2.H)]
    cx, cy = sun
    for y in range(g if horizon_cut else g2.H):
        for x in range(W):
            d2 = (x - cx) ** 2 + (y - cy) ** 2
            for tok, r in zip(("sun1", "sun2", "sun3"), radii):
                if d2 <= r * r:
                    grid[y][x] = tok
                    break
    g2.shadow(grid, g2.glyphs(x0, False), g, sh_h, 2, "shadow")   # sun right, so the shadow leans left
    for (x, y), (k, s) in g2.glyphs(x0).items():
        grid[y0 + y][x] = "knot" if k == "knot" else ("line1", "line2", "line3")[s]
    return grid

SQUARE = dict(W=64, x0=15, y0=11, sh_h=21, sun=(63.5, -0.5), radii=(5, 8, 11), horizon_cut=True)
BLUE, SKY, VIOLET, GREEN, DKGREEN, NAVY = "#2340E8", "#2D9BF0", "#7A2BF0", "#22B86B", "#0E6B43", "#1A2A9C"
DEEP, PALE = "#4A14B0", "#8ED0FF"
WAYS = {   # sky, ground, shadow
    "qp-day-cobalt": (BLUE, CREAM, BLUE),
    "qp-day-sky":    (SKY, CREAM, BLUE),
    "qp-day-violet": (VIOLET, CREAM, VIOLET),
    "qp-day-grass":  (BLUE, GREEN, DKGREEN),
    "qp-sky-on-violet":  (SKY, VIOLET, DEEP),      # baby blue sky, violet ground
    "qp-violet-on-sky":  (VIOLET, SKY, VIOLET),    # violet sky, baby blue ground
    "qp-violet-on-pale": (VIOLET, PALE, VIOLET),   # violet sky, paler blue ground
    "qp-sky-on-violet-cut": (SKY, VIOLET, SKY),    # shadow is the sky colour
}
lines = ["// qp in three lines, a sun to the right, a slanted shadow that reads db. Generated by gen3.py."]
order = ["wall", "floor", "shadow", "sun3", "sun2", "sun1", "line1", "line2", "line3", "knot"]
rects = g2.rle(build(**SQUARE))
for name, (sky, ground, shade) in WAYS.items():
    cols = {**COLS, "wall": sky, "floor": ground, "shadow": shade}
    lines.append(json.dumps({"type": "palette", "name": name, "colors": {"_": "transparent", **{k: cols[k] for k in order}},
        "roles": {k: ("anchor" if k.startswith("line") else "shadow" if k == "shadow" else "highlight" if k == "knot" or k.startswith("sun") else "fill") for k in order}}, separators=(",", ":")))
for name in WAYS:
    regions = {t: {"union": rects[t], "z": i + 1} for i, t in enumerate(order) if t in rects}
    lines.append(json.dumps({"type": "sprite", "name": name, "size": [64, g2.H], "palette": name, "regions": regions}, separators=(",", ":")))
open("qp-sun.pxl", "w").write("\n".join(lines) + "\n")

# The four violet and baby-blue pairings: a 2x2 grid, and one mark cycling through all four.
FOUR = ["qp-sky-on-violet", "qp-violet-on-sky", "qp-sky-on-violet-cut", "qp-violet-on-pale"]
extra = []
for step in range(4):                                  # each step turns the colours one place clockwise
    k = [FOUR[(i - step) % 4] for i in range(4)]       # top left, top right, bottom right, bottom left
    extra.append({"type": "composition", "name": f"qp-quad-{step}", "size": [128, 128], "cell_size": [64, 64],
                  "sprites": {"a": k[0], "b": k[1], "c": k[2], "d": k[3]}, "layers": [{"map": ["ab", "dc"]}]})
extra.append({"type": "animation", "name": "qp-cycle", "frames": FOUR, "duration": 700, "loop": True})
with open("qp-sun.pxl", "a") as f:
    for obj in extra:
        f.write(json.dumps(obj, separators=(",", ":")) + "\n")
