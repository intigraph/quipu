#!/usr/bin/env python3
"""Generate qp-logo.pxl: the letters qp cast a shadow that reads db.

q and p flipped top-to-bottom ARE d and b, so a shadow thrown toward the
viewer spells the thing the command talks to. Bitmaps are drawn here and
run-length encoded into pixelsrc rect unions.
"""
import json

W = H = 64
T = 4            # stroke
BOWL = 14        # bowl outer size
TALL = 22        # x-height 14 + descender 8

def glyphs(x0, knots=True):
    """Return {(x,y): 'body'|'knot'} for qp with top-left at (x0, 0)."""
    px = {}
    def rect(x, y, w, h, tok="body"):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                px[(xx, yy)] = tok
    # q: bowl on the left, stem on the right
    rect(x0 + 2, 0, 10, T); rect(x0 + 2, BOWL - T, 10, T); rect(x0, 2, T, BOWL - 4)
    rect(x0 + 10, 0, T, TALL)
    # p: stem on the left, bowl on the right
    p0 = x0 + BOWL + 4
    rect(p0, 0, T, TALL)
    rect(p0 + 2, 0, 10, T); rect(p0 + 2, BOWL - T, 10, T); rect(p0 + 10, 2, T, BOWL - 4)
    # counting knots on the hanging cords (descenders): two on q, one on p
    if knots:
        for y in (15, 19):
            rect(x0 + 9, y, T + 2, 2, "knot")
        rect(p0 - 1, 17, T + 2, 2, "knot")
    return px

def panel(grid, rim, wall, floor, ground):
    def rr(x, y, w, h, r, tok):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                dx = max(x + r - xx, xx - (x + w - 1 - r), 0)
                dy = max(y + r - yy, yy - (y + h - 1 - r), 0)
                if dx * dx + dy * dy <= r * r:
                    grid[yy][xx] = tok
    rr(2, 2, 60, 60, 6, rim)
    rr(4, 4, 56, 56, 4, wall)
    for yy in range(ground, 60):
        for xx in range(4, 60):
            if grid[yy][xx] == wall:
                grid[yy][xx] = floor

def build(kind, framed=True):
    grid = [["_"] * W for _ in range(H)]
    if kind == "mirror":
        x0, y0, sh_h, shear = 16, 9, TALL, 0
    else:
        x0, y0, sh_h, shear = 21, 13, 16, 2   # 1px left per `shear` rows
    ground = y0 + TALL
    if framed:
        panel(grid, "rim", "wall", "floor", ground)
    g = glyphs(x0)
    stems = glyphs(x0, knots=False)   # knots bulge past the cord; the shadow stays clean
    # shadow: flip around the ground line, squash, shear toward the viewer
    for r in range(sh_h):
        src = TALL - 1 - (r * TALL) // sh_h
        dx = -(r // shear) if shear else 0
        for (x, y), _ in stems.items():
            if y == src:
                grid[ground + r][x + dx] = "shadow"
    for (x, y), tok in g.items():
        grid[y0 + y][x] = tok
    return grid

def rle(grid):
    """Greedy rects per token: horizontal runs merged down identical rows."""
    out, open_runs = {}, {}
    for y in range(H + 1):
        runs = set()
        if y < H:
            x = 0
            while x < W:
                t = grid[y][x]; s = x
                while x < W and grid[y][x] == t:
                    x += 1
                if t != "_":
                    runs.add((t, s, x - s))
        for key in sorted(open_runs):
            if key not in runs:
                t, s, w = key; ys = open_runs.pop(key)
                out.setdefault(t, []).append({"rect": [s, ys, w, y - ys]})
        for key in sorted(runs):
            open_runs.setdefault(key, y)
    return out

PALETTES = {
    "qp-dark":  {"rim": "#F2E6CF", "wall": "#172B3B", "floor": "#294554", "shadow": "#10212F", "body": "#F2E6CF", "knot": "#EDB96E"},
    "qp-light": {"rim": "#172B3B", "wall": "#F2E6CF", "floor": "#E3D3B4", "shadow": "#95AFB4", "body": "#172B3B", "knot": "#E78E7D"},
    "qp-mark":  {"shadow": "#95AFB4", "body": "#68D4BF", "knot": "#EDB96E"},
}
ROLES = {"rim": "boundary", "wall": "fill", "floor": "fill", "shadow": "shadow", "body": "anchor", "knot": "highlight"}
ORDER = ["rim", "wall", "floor", "shadow", "body", "knot"]
SPRITES = [("qp-mirror", "mirror", True, "qp-dark"), ("qp-cast", "cast", True, "qp-dark"),
           ("qp-cast-light", "cast", True, "qp-light"), ("qp-mark", "cast", False, "qp-mark")]

lines = ["// qp casts db: the quipu command and the store behind it. Generated by gen.py."]
for name, cols in PALETTES.items():
    lines.append(json.dumps({"type": "palette", "name": name, "colors": {"_": "transparent", **cols},
                             "roles": {k: ROLES[k] for k in cols}}, separators=(",", ":")))
for name, kind, framed, pal in SPRITES:
    rects = rle(build(kind, framed))
    regions = {t: {"union": rects[t], "z": i + 1} for i, t in enumerate(ORDER) if t in rects}
    lines.append(json.dumps({"type": "sprite", "name": name, "size": [W, H], "palette": pal, "regions": regions},
                            separators=(",", ":")))
open("qp-logo.pxl", "w").write("\n".join(lines) + "\n")
