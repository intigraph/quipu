//! Generated book pages: the CLI command index (from the catalogue) and the
//! MCP tool index (from `quipu::mcp::tool_definitions()`).

use serde_json::Value;

use crate::about::about;
use crate::catalogue::{SPECS, is_group};

pub const CLI_PAGE: &str = "docs/book/src/reference/cli-commands.md";
pub const MCP_PAGE: &str = "docs/book/src/reference/mcp-tool-index.md";

const HEADER: &str = "<!-- Generated by quipu-docgen from the command catalogue and the MCP tool \
definitions. Do not edit: change the source and run \
`cargo run --features docgen --bin quipu-docgen`. -->\n\n";

/// The CLI command index, one section per command path in catalogue order.
pub fn cli_page() -> String {
    let mut out = String::from(HEADER);
    out.push_str("# CLI Command Index\n\n");
    out.push_str(
        "Every `quipu` command path with its syntax, generated from the same catalogue \
         that admits arguments, so it cannot list a command the binary refuses or miss \
         one it accepts. `qp` is the same binary. Every command also takes `--db <path>` \
         (default `.bobbin/quipu/quipu.db`). For explanations and examples see \
         [CLI Commands](cli.md); `man quipu-<command>` prints the same syntax.\n",
    );
    for spec in SPECS {
        let depth = spec.path.split_whitespace().count();
        let hashes = "#".repeat((depth + 1).min(4));
        out.push_str(&format!("\n{hashes} `qp {}`\n\n", spec.path));
        if let Some(text) = about(spec.path) {
            out.push_str(&format!("{text}.\n\n"));
        }
        if is_group(spec) {
            let children: Vec<String> = SPECS
                .iter()
                .filter(|s| {
                    s.path
                        .strip_prefix(spec.path)
                        .is_some_and(|t| t.starts_with(' ') && !t[1..].contains(' '))
                })
                .map(|s| format!("`{}`", s.path))
                .collect();
            out.push_str(&format!("Subcommands: {}.\n", children.join(", ")));
            continue;
        }
        let operands = if spec.operands.is_empty() {
            String::new()
        } else {
            format!(" {}", spec.operands)
        };
        out.push_str(&format!("```text\nqp {}{operands}\n```\n", spec.path));
        let values: Vec<String> = spec
            .values
            .split_whitespace()
            .map(|v| format!("`--{v} <VALUE>`"))
            .collect();
        if !values.is_empty() {
            out.push_str(&format!("\nValue options: {}.\n", values.join(", ")));
        }
        let switches: Vec<String> = spec
            .switches
            .split_whitespace()
            .map(|v| format!("`--{v}`"))
            .collect();
        if !switches.is_empty() {
            out.push_str(&format!("\nSwitches: {}.\n", switches.join(", ")));
        }
    }
    out
}

/// The MCP tool index: every served tool, alphabetical, with its parameters.
pub fn mcp_page(tools: &[Value]) -> String {
    let mut sorted: Vec<&Value> = tools.iter().collect();
    sorted.sort_by_key(|t| t["name"].as_str().unwrap_or_default().to_string());
    let mut out = String::from(HEADER);
    out.push_str("# MCP Tool Index\n\n");
    out.push_str(&format!(
        "All {} tools that `quipu mcp` and `quipu-server` serve in a build with the `owl` \
         feature, generated from the tool definitions. For connection details, workflows \
         and examples see [MCP Tools](mcp-tools.md).\n",
        sorted.len()
    ));
    for tool in sorted {
        let name = tool["name"].as_str().unwrap_or("?");
        out.push_str(&format!("\n## `{name}`\n\n"));
        out.push_str(&format!(
            "{}\n",
            one_line(tool["description"].as_str().unwrap_or(""))
        ));
        let schema = &tool["inputSchema"];
        let Some(props) = schema["properties"].as_object().filter(|p| !p.is_empty()) else {
            out.push_str("\nNo parameters.\n");
            continue;
        };
        let required: Vec<&str> = schema["required"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        out.push_str(
            "\n| Parameter | Type | Required | Description |\n| --- | --- | --- | --- |\n",
        );
        let mut names: Vec<&String> = props.keys().collect();
        names.sort();
        for param in names {
            let p = &props[param];
            out.push_str(&format!(
                "| `{param}` | {} | {} | {} |\n",
                type_of(p),
                if required.contains(&param.as_str()) {
                    "yes"
                } else {
                    "no"
                },
                cell(p["description"].as_str().unwrap_or(""))
            ));
        }
    }
    out
}

fn type_of(p: &Value) -> String {
    let base = match &p["type"] {
        Value::String(s) => s.clone(),
        Value::Array(a) => a
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" or "),
        _ if p.get("oneOf").is_some() || p.get("anyOf").is_some() => "varies".into(),
        _ => "any".into(),
    };
    match p["enum"].as_array() {
        Some(values) if !values.is_empty() => {
            let list: Vec<String> = values.iter().map(|v| format!("`{}`", plain(v))).collect();
            format!("{base}: {}", list.join(", "))
        }
        _ => base,
    }
}

fn plain(v: &Value) -> String {
    v.as_str().map_or_else(|| v.to_string(), str::to_string)
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// A Markdown table cell: one line, pipes escaped, no raw HTML or mdBook
/// directives.
fn cell(text: &str) -> String {
    one_line(text)
        .replace('|', "\\|")
        .replace('<', "&lt;")
        .replace("{{", "{ {")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cli_page_lists_every_path_with_its_syntax() {
        let page = cli_page();
        for spec in SPECS {
            assert!(
                page.contains(&format!("`qp {}`", spec.path)),
                "{}",
                spec.path
            );
        }
        assert!(page.contains("qp shapes load <name> <file.ttl>"));
        assert!(page.ends_with('\n') && !page.ends_with("\n\n"));
    }

    #[test]
    fn mcp_page_documents_every_tool_and_required_params() {
        let tools = quipu::mcp::tool_definitions();
        let page = mcp_page(&tools);
        for tool in &tools {
            let name = tool["name"].as_str().unwrap();
            assert!(page.contains(&format!("## `{name}`")), "{name}");
        }
        assert!(page.contains("| `query` | string | yes |"));
        assert!(page.ends_with('\n') && !page.ends_with("\n\n"));
    }

    #[test]
    fn cells_cannot_break_the_table() {
        assert_eq!(cell("a | b\n c <x> {{y}}"), "a \\| b c &lt;x> { {y}}");
    }
}
