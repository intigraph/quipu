//! Per-option descriptions shared by admission help, the book and man pages.

pub(crate) fn option_help(path: &str, name: &str) -> Option<&'static str> {
    match (path, name) {
        ("db respace", "into") => Some("New integer namespace space number"),
        ("db attach", "list") => Some("List mounted read-only databases"),
        ("render", "path") => Some("Relative output path template"),
        ("changes", "from") => Some("First transaction to include"),
        ("audit", "from") => Some("Base Git revision for the audit"),
        ("audit", "to") => Some("Tip Git revision for the audit"),
        ("migrate-vectors", "from") => Some("Source vector backend"),
        ("migrate-vectors", "to") => Some("Destination vector backend"),
        ("project", "from") => Some("Start entity IRI for shortest-path projection"),
        ("project", "to") => Some("Destination entity IRI for shortest-path projection"),
        ("share", "project") => Some("Export this repository's project graph to .quipu/graph"),
        ("prime", "full") => Some("Print the full agent primer"),
        ("propose plan", "format") => Some("Plan output format: text or json"),
        ("propose plan", "risk-threshold") => {
            Some("Fail the plan above this 0-100 risk score (default: the deployment threshold)")
        }
        ("propose accept", "risk-threshold") => {
            Some("Refuse acceptance above this 0-100 risk score (default: the deployment threshold)")
        }
        ("propose accept", "accept-risk") => {
            Some("Accept despite a plan over the risk threshold; requires --reason")
        }
        ("propose accept", "reason") => Some("Why an over-threshold plan is accepted; recorded with the decision"),
        _ => common(name),
    }
}

