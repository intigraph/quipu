// Build-time validation runs the shipped native receiver once, outside startup.
// The resulting proof and immutable store ship with this exact Pages build.
import { readFile, writeFile, mkdtemp, copyFile, rm } from "node:fs/promises";
import { resolve, join } from "node:path";
import { tmpdir } from "node:os";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";

const site = resolve(process.argv[2] || "docs/book/src/explore");
const hash = bytes => "sha256:" + createHash("sha256").update(bytes).digest("hex");
const temp = await mkdtemp(join(tmpdir(), "explorer-default-"));
try {
  // .mjs makes the downloaded release glue unambiguously ESM in Node too.
  await copyFile(join(site, "pkg/quipu_wasm_explorer.js"), join(temp, "engine.mjs"));
  const engine = await import(pathToFileURL(join(temp, "engine.mjs")));
  if (!engine.Explorer.prototype.verifiedSnapshot) {
    if (!process.argv.includes("--allow-legacy")) throw Error("released engine has no verified snapshot API");
    await rm(join(site, "default-store.db.gz"), { force: true });
    await writeFile(join(site, "default-pack-proof.js"), "export default null;\n");
    console.log("Legacy release: full browser receiving remains required; no fast-load proof emitted.");
  } else {
    const wasm = await readFile(join(site, "pkg/quipu_wasm_explorer_bg.wasm"));
    await engine.default({ module_or_path: wasm });
    await copyFile(join(site, "constellation-queries.js"), join(temp, "queries.mjs"));
    const { constellationQueries } = await import(pathToFileURL(join(temp, "queries.mjs")));
    const queries = constellationQueries();
    const pack = await readFile(join(site, "repository.pendant.tar.gz"));
    const explorer = engine.Explorer.loadPendant(pack, "Pages default pack", new Date().toISOString());
    try {
      const report = JSON.parse(explorer.loadReport());
      if (!report.shacl_compiled || typeof report.import?.validation?.conforms !== "boolean"
          || report.import?.promotion?.eligible !== true
          || report.import?.validation?.blocking !== false || report.promotion?.outcome !== "promoted") {
        throw Error("Default-pack validation refused: " + JSON.stringify({ shacl_compiled: report.shacl_compiled,
          validation: report.import?.validation, promotion: report.promotion }));
      }
      // verifiedSnapshot refuses a blocked/non-promoted/edited store.
      const snapshot = gzipSync(explorer.verifiedSnapshot(), { level: 9, mtime: 0 });
      const proof = { schema: "quipu.explorer-default/v1", pack_sha256: hash(pack),
        wasm_sha256: hash(wasm), snapshot_sha256: hash(snapshot),
        shapes_sha256: report.manifest.shapes_hash, conforms: report.import.validation.conforms,
        snapshot: "./default-store.db.gz", report,
        views: { queries, knowledge: JSON.parse(explorer.query(queries.knowledge)),
          files: JSON.parse(explorer.query(queries.files)) } };
      await writeFile(join(site, "default-store.db.gz"), snapshot);
      await writeFile(join(site, "default-pack-proof.js"),
        "// Generated by the Pages build after full native receiving.\nexport default " + JSON.stringify(proof) + ";\n");
      console.log(JSON.stringify({ schema: proof.schema, pack_sha256: proof.pack_sha256,
        conforms: proof.conforms, shapes_sha256: proof.shapes_sha256, snapshot_bytes: snapshot.length }));
    } finally { explorer.free(); }
  }
} finally { await rm(temp, { recursive: true, force: true }); }
